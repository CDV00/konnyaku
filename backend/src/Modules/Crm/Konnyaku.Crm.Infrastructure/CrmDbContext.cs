using Konnyaku.Application.Privacy;
using Konnyaku.Application.Tenancy;
using Konnyaku.Crm.Application;
using Konnyaku.Crm.Contracts;
using Konnyaku.Crm.Domain;
using Konnyaku.Infrastructure.Auditing;
using Konnyaku.Infrastructure.Persistence;
using Konnyaku.Infrastructure.Tenancy;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Design;
using Microsoft.EntityFrameworkCore.Storage;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;

namespace Konnyaku.Crm.Infrastructure;

public sealed class CrmDbContext(DbContextOptions<CrmDbContext> options, ITenantContext tenant)
    : ModuleDbContext(options, tenant), ICrmDbContext
{
    public const string SchemaName = "crm";

    public override string Schema => SchemaName;

    public DbSet<Lead> Leads => Set<Lead>();

    public DbSet<StudentProfile> Students => Set<StudentProfile>();

    public DbSet<PersonalDataAccess> PersonalDataAccesses => Set<PersonalDataAccess>();

    public DbSet<DataSubjectRequest> DataSubjectRequests => Set<DataSubjectRequest>();

    /// <summary>
    /// Search column of leads and students: name, phone, email and guardian, lower case and without accents (the
    /// trigram index answers <c>LIKE '%an%'</c>). Generated by PostgreSQL, so every write and every anonymization keeps it right.
    /// </summary>
    internal const string StudentSearchSql =
        "public.kk_unaccent(lower(full_name || ' ' || coalesce(phone, '') || ' ' || coalesce(email, '') || ' ' || coalesce(guardian_name, '')))";

    internal const string LeadSearchSql =
        "public.kk_unaccent(lower(student_name || ' ' || coalesce(phone, '') || ' ' || coalesce(email, '') || ' ' || coalesce(guardian_name, '')))";

    public Task<IDbContextTransaction> BeginTransactionAsync(CancellationToken cancellationToken) =>
        Database.BeginTransactionAsync(cancellationToken);
    public DbSet<CaptchaRedemption> CaptchaRedemptions => Set<CaptchaRedemption>();

    protected override void ConfigureModel(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Lead>(b =>
        {
            b.ToTable("lead");
            b.HasKey(x => x.Id);
            b.Property(x => x.StudentName).HasMaxLength(200);
            b.Property(x => x.GuardianName).HasMaxLength(200);
            b.Property(x => x.Phone).HasMaxLength(20);
            b.Property(x => x.Email).HasMaxLength(320);
            b.Property(x => x.LanguageCode).HasMaxLength(20);
            b.Property(x => x.Goal).HasMaxLength(500);
            b.Property(x => x.PreferredSchedule).HasMaxLength(500);
            b.Property(x => x.Source).HasMaxLength(40);
            b.Property(x => x.Utm).HasJsonConversion();
            b.Property(x => x.ConsentVersion).HasMaxLength(40);
            b.Property(x => x.Locale).HasMaxLength(20);
            b.Property(x => x.Status).HasConversion<string>().HasMaxLength(20);
            b.Ignore(x => x.IsOpen);
            b.Property(x => x.SearchText).HasComputedColumnSql(LeadSearchSql, stored: true);
            b.HasIndex(x => new { x.TenantId, x.Phone });
            b.HasIndex(x => new { x.TenantId, x.Email });
            b.HasIndex(x => new { x.TenantId, x.Status, x.FollowUpDueAt });
            b.HasIndex(x => new { x.TenantId, x.CreatedAt });
            b.HasIndex(x => new { x.TenantId, x.UpdatedAt }).HasFilter("anonymized_at IS NULL");
            b.HasIndex(x => x.SearchText).HasMethod("gin").HasOperators("gin_trgm_ops");
        });
        modelBuilder.Entity<StudentProfile>(b =>
        {
            b.ToTable("student_profile");
            b.HasKey(x => x.Id);
            b.Property(x => x.FullName).HasMaxLength(200);
            b.Property(x => x.GuardianName).HasMaxLength(200);
            b.Property(x => x.Phone).HasMaxLength(20);
            b.Property(x => x.Email).HasMaxLength(320);
            b.Property(x => x.CommunicationLocale).HasMaxLength(20);
            b.Property(x => x.SearchText).HasComputedColumnSql(StudentSearchSql, stored: true);
            b.HasIndex(x => new { x.TenantId, x.UserId }).IsUnique().HasFilter("user_id IS NOT NULL");
            b.HasIndex(x => new { x.TenantId, x.FullName, x.Id });
            b.HasIndex(x => new { x.TenantId, x.CreatedAt });
            b.HasIndex(x => new { x.TenantId, x.HomeBranchId });
            b.HasIndex(x => x.SearchText).HasMethod("gin").HasOperators("gin_trgm_ops");
        });
        modelBuilder.Entity<PersonalDataAccess>(b =>
        {
            b.ToTable("personal_data_access");
            b.HasKey(x => x.Id);
            b.Property(x => x.Action).HasConversion<string>().HasMaxLength(30);
            b.Property(x => x.SubjectType).HasMaxLength(20);
            b.Property(x => x.Purpose).HasMaxLength(40);
            b.Property(x => x.Filter).HasJsonConversion();
            b.Property(x => x.ActorName).HasMaxLength(200);
            b.Property(x => x.IpAddress).HasMaxLength(64);
            b.HasIndex(x => new { x.TenantId, x.OccurredAt });
            b.HasIndex(x => new { x.TenantId, x.ActorId, x.OccurredAt });
            b.HasIndex(x => new { x.TenantId, x.SubjectId });
        });
        modelBuilder.Entity<DataSubjectRequest>(b =>
        {
            b.ToTable("data_subject_request");
            b.HasKey(x => x.Id);
            b.Property(x => x.SubjectType).HasMaxLength(20);
            b.Property(x => x.Type).HasConversion<string>().HasMaxLength(30);
            b.Property(x => x.Status).HasConversion<string>().HasMaxLength(20);
            b.Property(x => x.Note).HasMaxLength(1000);
            b.Property(x => x.Resolution).HasMaxLength(1000);
            b.Property(x => x.ResolvedByName).HasMaxLength(200);
            b.HasIndex(x => new { x.TenantId, x.Status, x.DueAt });
            b.HasIndex(x => new { x.TenantId, x.SubjectId });
        });
        modelBuilder.Entity<CaptchaRedemption>(b =>
        {
            b.ToTable("captcha_redemption");
            b.HasKey(x => x.Id);
            b.Property(x => x.Challenge).HasMaxLength(64);
            b.HasIndex(x => new { x.TenantId, x.Challenge }).IsUnique();
            b.HasIndex(x => new { x.TenantId, x.ExpiresAt });
        });
        modelBuilder.AddChangeLog();
    }
}

public static class CrmInfrastructure
{
    public static IServiceCollection AddCrmInfrastructure(this IServiceCollection services, IConfiguration configuration, string connectionName)
    {
        services.AddModuleDbContext<CrmDbContext>(configuration, connectionName, CrmDbContext.SchemaName);
        services.AddScoped<ICrmDbContext>(sp => sp.GetRequiredService<CrmDbContext>());
        services.AddScoped<CrmQueries>();
        services.AddScoped<ICrmApi>(sp => sp.GetRequiredService<CrmQueries>());
        services.AddScoped<CrmListQueries>();
        services.AddScoped<PersonalDataLog>();
        services.AddScoped<RevealHandlers>();
        services.AddScoped<ExportHandlers>();
        services.AddScoped<PrivacyHandlers>();
        services.AddScoped<LeadRetention>();
        services.AddScoped<IPersonalDataSource, CrmPersonalData>();
        services.AddSingleton(configuration.GetSection("Privacy").Get<PrivacySettings>() ?? new PrivacySettings());
        services.AddScoped<ICrmUsageApi, CrmUsageQueries>();
        services.AddScoped<ICrmContactsApi, CrmContacts>();
        services.AddSingleton(TimeProvider.System);
        return services;
    }

    /// <summary>Worker only: the daily lead retention job.</summary>
    public static IServiceCollection AddCrmWorker(this IServiceCollection services)
    {
        services.AddSingleton<LeadRetentionService>();
        services.AddHostedService(sp => sp.GetRequiredService<LeadRetentionService>());
        return services;
    }
}

internal sealed class CrmDesignTimeFactory : IDesignTimeDbContextFactory<CrmDbContext>
{
    public CrmDbContext CreateDbContext(string[] args) => new(
        new DbContextOptionsBuilder<CrmDbContext>()
            .UseNpgsql("Host=localhost;Database=design_time", o => o.MigrationsHistoryTable("__ef_migrations_history", CrmDbContext.SchemaName))
            .UseSnakeCaseNamingConvention()
            .Options,
        new TenantContext());
}
