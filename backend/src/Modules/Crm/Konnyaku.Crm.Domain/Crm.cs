using Konnyaku.SharedKernel;

namespace Konnyaku.Crm.Domain;

/// <summary>A prospective student who filled the public registration form (or was entered by staff).</summary>
public sealed class Lead : Entity, ITenantOwned, IAuditable
{
    public static readonly TimeSpan CallBackWithin = TimeSpan.FromMinutes(15);

    private Lead()
    {
    }

    public Guid TenantId { get; private set; }

    [PersonalData(PersonalDataKind.Name)]
    public string StudentName { get; private set; } = string.Empty;

    [PersonalData(PersonalDataKind.BirthYear)]
    public int? BirthYear { get; private set; }

    [PersonalData(PersonalDataKind.Name)]
    public string? GuardianName { get; private set; }

    [PersonalData(PersonalDataKind.Phone)]
    public string? Phone { get; private set; }

    [PersonalData(PersonalDataKind.Email)]
    public string? Email { get; private set; }

    public string LanguageCode { get; private set; } = string.Empty;
    public string? Goal { get; private set; }
    public Guid? PreferredBranchId { get; private set; }
    public string? PreferredSchedule { get; private set; }
    public string Source { get; private set; } = "web";
    public Dictionary<string, string> Utm { get; private set; } = [];
    public string ConsentVersion { get; private set; } = string.Empty;
    public DateTimeOffset ConsentAt { get; private set; }
    public string Locale { get; private set; } = "vi";
    public LeadStatus Status { get; private set; }
    public Guid? AssignedConsultantId { get; private set; }
    public DateTimeOffset? FollowUpDueAt { get; private set; }
    public DateTimeOffset CreatedAt { get; private set; }
    public DateTimeOffset UpdatedAt { get; private set; }

    /// <summary>When the personal data was erased (request or retention); the lead stays as an anonymous row in the statistics.</summary>
    public DateTimeOffset? AnonymizedAt { get; private set; }

    /// <summary>Folded name, phone, email and guardian (generated by the database) for accent-insensitive search.</summary>
    public string SearchText { get; private set; } = string.Empty;

    public bool IsOpen => Status is LeadStatus.New or LeadStatus.Contacted;

    /// <summary>
    /// Erases the personal data (name, birth year, guardian, contact, free-text goal and schedule) and closes the lead.
    /// Language, branch, source, consent version and dates stay for statistics: they identify no one.
    /// </summary>
    public void Anonymize(DateTimeOffset now)
    {
        StudentName = AnonymousName(Id);
        BirthYear = null;
        GuardianName = null;
        Phone = null;
        Email = null;
        Goal = null;
        PreferredSchedule = null;
        Utm = [];
        if (IsOpen)
        {
            Status = LeadStatus.Lost;
        }

        FollowUpDueAt = null;
        AnonymizedAt ??= now;
        UpdatedAt = now;
    }

    /// <summary>The name an anonymized record keeps: short, the same for the same record, identifying no one.</summary>
    public static string AnonymousName(Guid id) => "#" + id.ToString("N")[^8..];

    Guid IAuditable.AuditSubjectId => Id;

    /// <summary>Staff correct the details of an open lead (a closed lead is history) and may hand it to another consultant.</summary>
    public Result<Lead> Edit(LeadDetails details, Guid? consultantId, DateTimeOffset now)
    {
        if (!IsOpen)
        {
            return Error.Conflict("crm.lead_closed");
        }

        var validation = Validate(details, now);
        if (validation is not null)
        {
            return validation;
        }

        Apply(details with { Utm = Utm, Locale = Locale }, now);
        if (consultantId != AssignedConsultantId)
        {
            AssignTo(consultantId, now);
        }

        return this;
    }

    public static Result<Lead> Create(LeadDetails details, string source, string consentVersion, DateTimeOffset now)
    {
        var validation = Validate(details, now);
        if (validation is not null)
        {
            return validation;
        }

        if (string.IsNullOrWhiteSpace(consentVersion))
        {
            return Error.Validation("crm.consent_required");
        }

        var lead = new Lead
        {
            Source = source,
            ConsentVersion = consentVersion,
            ConsentAt = now,
            Status = LeadStatus.New,
            CreatedAt = now,
        };
        lead.Apply(details, now);
        return lead;
    }

    /// <summary>The same person submitting again refreshes the open lead instead of creating a duplicate.</summary>
    public Result<Lead> Resubmit(LeadDetails details, DateTimeOffset now)
    {
        var validation = Validate(details, now);
        if (validation is not null)
        {
            return validation;
        }

        Apply(details, now);
        return this;
    }

    public void AssignTo(Guid? consultantId, DateTimeOffset now)
    {
        AssignedConsultantId = consultantId;
        FollowUpDueAt = now.Add(CallBackWithin);
    }

    public Result<Lead> ChangeStatus(LeadStatus status, DateTimeOffset now)
    {
        if (!IsOpen)
        {
            return Error.Conflict("crm.lead_closed");
        }

        Status = status;
        UpdatedAt = now;
        if (!IsOpen)
        {
            FollowUpDueAt = null;
        }

        return this;
    }

    private void Apply(LeadDetails details, DateTimeOffset now)
    {
        StudentName = details.StudentName.Trim();
        BirthYear = details.BirthYear;
        GuardianName = details.GuardianName?.Trim();
        Phone = NormalizePhone(details.Phone);
        Email = details.Email?.Trim().ToLowerInvariant();
        LanguageCode = details.LanguageCode.Trim();
        Goal = details.Goal?.Trim();
        PreferredBranchId = details.PreferredBranchId;
        PreferredSchedule = details.PreferredSchedule?.Trim();
        Utm = details.Utm?.ToDictionary() ?? [];
        Locale = details.Locale ?? "vi";
        UpdatedAt = now;
    }

    private static Error? Validate(LeadDetails d, DateTimeOffset now)
    {
        if (string.IsNullOrWhiteSpace(d.StudentName))
        {
            return Error.Validation("crm.student_name_required");
        }

        if (string.IsNullOrWhiteSpace(d.Phone) && string.IsNullOrWhiteSpace(d.Email))
        {
            return Error.Validation("crm.contact_required");
        }

        if (string.IsNullOrWhiteSpace(d.LanguageCode))
        {
            return Error.Validation("crm.language_required");
        }

        var age = d.BirthYear is { } year ? now.Year - year : (int?)null;
        if (age is < 0 or > 120)
        {
            return Error.Validation("crm.birth_year_invalid");
        }

        // Minors need a guardian (contact and contract); see docs 7.9.4.
        if (age < 18 && string.IsNullOrWhiteSpace(d.GuardianName))
        {
            return Error.Validation("crm.guardian_required");
        }

        return null;
    }

    public static string? NormalizePhone(string? phone)
    {
        if (string.IsNullOrWhiteSpace(phone))
        {
            return null;
        }

        var digits = new string(phone.Where(c => char.IsDigit(c) || c == '+').ToArray());
        return digits.StartsWith("+84", StringComparison.Ordinal) ? "0" + digits[3..] : digits;
    }
}

public sealed record LeadDetails(
    string StudentName, int? BirthYear, string? GuardianName, string? Phone, string? Email, string LanguageCode,
    string? Goal, Guid? PreferredBranchId, string? PreferredSchedule, IReadOnlyDictionary<string, string>? Utm, string? Locale);

public enum LeadStatus
{
    New,
    Contacted,
    Converted,
    Lost,
}

/// <summary>Student record of a tenant. Linked to a sign-in account (Identity user) when one is issued.</summary>
public sealed class StudentProfile : Entity, ITenantOwned, IAuditable
{
    private StudentProfile()
    {
    }

    public Guid TenantId { get; private set; }

    [PersonalData(PersonalDataKind.Name)]
    public string FullName { get; private set; } = string.Empty;

    [PersonalData(PersonalDataKind.BirthYear)]
    public int? BirthYear { get; private set; }

    [PersonalData(PersonalDataKind.Name)]
    public string? GuardianName { get; private set; }

    [PersonalData(PersonalDataKind.Phone)]
    public string? Phone { get; private set; }

    [PersonalData(PersonalDataKind.Email)]
    public string? Email { get; private set; }

    public Guid? HomeBranchId { get; private set; }
    public Guid? UserId { get; private set; }
    public string CommunicationLocale { get; private set; } = "vi";
    public Guid? LeadId { get; private set; }
    public DateTimeOffset CreatedAt { get; private set; }

    /// <summary>An inactive student (left the center) keeps enrollments, orders and history but cannot buy or enroll again.</summary>
    public bool IsActive { get; private set; } = true;

    /// <summary>When the personal data was erased on request. Enrollments, attendance, orders and the lesson ledger stay.</summary>
    public DateTimeOffset? AnonymizedAt { get; private set; }

    /// <summary>Folded name, phone, email and guardian (generated by the database) for accent-insensitive search.</summary>
    public string SearchText { get; private set; } = string.Empty;

    Guid IAuditable.AuditSubjectId => Id;

    /// <summary>
    /// Erasure request: overwrites name, birth year, guardian and contact details. Only a student who left (inactive) can
    /// be anonymized, so no class still expects them; the record id stays, so lesson ledger, orders and attendance (kept
    /// for accounting) remain consistent without naming anyone.
    /// </summary>
    public Result<StudentProfile> Anonymize(DateTimeOffset now)
    {
        if (IsActive)
        {
            return Error.Conflict("crm.student_active");
        }

        FullName = Lead.AnonymousName(Id);
        BirthYear = null;
        GuardianName = null;
        Phone = null;
        Email = null;
        AnonymizedAt ??= now;
        return this;
    }

    public Result<StudentProfile> Update(string fullName, int? birthYear, string? guardianName, string? phone, string? email,
        Guid? homeBranchId, string communicationLocale, DateTimeOffset now)
    {
        if (AnonymizedAt is not null)
        {
            return Error.Conflict("crm.student_anonymized");
        }

        if (string.IsNullOrWhiteSpace(fullName))
        {
            return Error.Validation("crm.student_name_required");
        }

        if (birthYear is { } year && now.Year - year is < 0 or > 120)
        {
            return Error.Validation("crm.birth_year_invalid");
        }

        FullName = fullName.Trim();
        BirthYear = birthYear;
        GuardianName = string.IsNullOrWhiteSpace(guardianName) ? null : guardianName.Trim();
        Phone = Lead.NormalizePhone(phone);
        Email = string.IsNullOrWhiteSpace(email) ? null : email.Trim().ToLowerInvariant();
        HomeBranchId = homeBranchId;
        CommunicationLocale = string.IsNullOrWhiteSpace(communicationLocale) ? CommunicationLocale : communicationLocale;
        return this;
    }

    public Result<StudentProfile> SetActive(bool active)
    {
        if (active && AnonymizedAt is not null)
        {
            return Error.Conflict("crm.student_anonymized");
        }

        IsActive = active;
        return this;
    }

    public static Result<StudentProfile> Create(
        string fullName, int? birthYear, string? guardianName, string? phone, string? email, Guid? homeBranchId,
        string communicationLocale, Guid? leadId, DateTimeOffset now)
    {
        if (string.IsNullOrWhiteSpace(fullName))
        {
            return Error.Validation("crm.student_name_required");
        }

        return new StudentProfile
        {
            FullName = fullName.Trim(),
            BirthYear = birthYear,
            GuardianName = guardianName?.Trim(),
            Phone = Lead.NormalizePhone(phone),
            Email = email?.Trim().ToLowerInvariant(),
            HomeBranchId = homeBranchId,
            CommunicationLocale = communicationLocale,
            LeadId = leadId,
            CreatedAt = now,
            IsActive = true,
        };
    }

    public void LinkAccount(Guid userId) => UserId = userId;
}

/// <summary>
/// A captcha challenge already used to accept a public form. The unique (tenant, challenge) index makes every
/// solved challenge single-use; rows past <see cref="ExpiresAt"/> are useless and get purged.
/// </summary>
public sealed class CaptchaRedemption : Entity, ITenantOwned
{
    private CaptchaRedemption()
    {
    }

    public CaptchaRedemption(string challenge, DateTimeOffset expiresAt)
    {
        Challenge = challenge;
        ExpiresAt = expiresAt;
    }

    public Guid TenantId { get; private set; }
    public string Challenge { get; private set; } = string.Empty;
    public DateTimeOffset ExpiresAt { get; private set; }
}
